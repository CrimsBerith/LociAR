/**
 * Admin panel languages. Keys are the English source strings, so English needs no table and a
 * missing Turkish entry falls back to English. `tests/i18n.test.mjs` checks every literal key used
 * in the panel has a Turkish entry.
 */
export type Lang = 'en' | 'tr';
export const LANGS: readonly Lang[] = ['tr', 'en'];
export const LANG_COOKIE = 'lociar_admin_lang';

/** Saved choice first; otherwise Turkish browsers get Turkish and everyone else English. */
export function resolveLang(cookie?: string | null, acceptLanguage?: string | null): Lang {
  if (cookie === 'tr' || cookie === 'en') return cookie;
  const first = (acceptLanguage ?? '').split(',')[0]?.trim().toLowerCase() ?? '';
  return first.startsWith('tr') ? 'tr' : 'en';
}

export function localeFor(lang: Lang): string {
  return lang === 'tr' ? 'tr-TR' : 'en-US';
}

export type Translate = (source: string, vars?: Record<string, string | number | null | undefined>) => string;

export function translator(lang: Lang): Translate {
  return (source, vars) => {
    let text = translateText(lang, source);
    if (vars) text = text.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key] ?? '') : match));
    return text;
  };
}

/** True when the Turkish table (or the error-code table) covers this source string. */
export function hasTurkish(source: string): boolean {
  return Object.hasOwn(TR, source) || Object.hasOwn(CODES, source);
}

function translateText(lang: Lang, source: string): string {
  if (typeof source !== 'string' || !source) return source;
  const code = CODES[source];
  // Keep the code visible next to the readable text for support and debugging.
  if (code) return `${lang === 'tr' ? code[1] : code[0]} (${source})`;
  if (lang === 'en') return source;
  const direct = TR[source];
  if (direct !== undefined) return direct;
  for (const [pattern, replace] of PATTERNS) {
    const match = pattern.exec(source);
    if (match) return replace(match);
  }
  return source;
}

// Generic API validation messages ("reason must be between 8 and 1000 characters").
const PATTERNS: Array<[RegExp, (match: RegExpExecArray) => string]> = [
  [/^(\w+) must be between (\d+) and (\d+) characters$/, m => `${fieldName(m[1])} ${m[2]}–${m[3]} karakter olmalı`],
  [/^(\w+) must be a string$/, m => `${fieldName(m[1])} metin olmalı`],
  [/^(\w+) must be a UUID$/, m => `${fieldName(m[1])} geçerli bir UUID olmalı`],
  [/^(\w+) must be a non-negative integer$/, m => `${fieldName(m[1])} sıfır veya pozitif tam sayı olmalı`],
];

function fieldName(field: string): string {
  return TR[field] ?? FIELD_NAMES[field] ?? field;
}

